import puppeteer from 'puppeteer-core'
import { writeFile } from 'node:fs/promises'
const browser = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, pipe: true, timeout: 15000, args: ['--no-first-run', '--no-default-browser-check'] })
try {
  const page = await browser.newPage()
  const errors = []
  const checks = []
  page.on('pageerror', error => errors.push(error.message))
  const check = (name, passed) => { checks.push({ name, passed: Boolean(passed) }); if (!passed) throw new Error(`FAIL: ${name}`); console.log(`PASS: ${name}`) }
  const wait = () => new Promise(resolve => setTimeout(resolve, 150))
  await page.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'reduce' }, { name: 'prefers-color-scheme', value: 'light' }])
  await page.setViewport({ width: 1440, height: 1000 })
  await page.goto('http://127.0.0.1:5174', { waitUntil: 'networkidle0', timeout: 15000 })
  check('One headline and four feature cards', await page.evaluate(() => document.querySelectorAll('h1').length === 1 && document.querySelectorAll('.feature-card').length === 4))
  check('Navigation anchors exist', await page.evaluate(() => [...document.querySelectorAll('.main-nav a')].every(a => document.querySelector(a.getAttribute('href')))))
  check('Map water stays distinct from the blue route', await page.$eval('.map-drawing > path:first-of-type', el => getComputedStyle(el).stroke === 'rgb(164, 196, 220)'))
  for (const width of [320, 360, 375, 560, 768, 900, 1024, 1280, 1440, 1920]) {
    await page.setViewport({ width, height: 900 })
    check(`No page overflow at ${width}px`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    if (width === 320) check('Closing action fits on one line at 320px', await page.$eval('.closing-banner .button', el => el.getBoundingClientRect().height <= 56))
    if (width <= 560) check(`Readable feature cards at ${width}px`, await page.$eval('.feature-card', el => el.getBoundingClientRect().width >= 260))
  }
  await page.setViewport({ width: 1280, height: 800 })
  check('Hero action visible at 1280x800', await page.$eval('.hero-actions .button', el => el.getBoundingClientRect().bottom <= 800))
  for (let i = 0; i < 5; i++) {
    const pins = await page.$$('.map-pin')
    await pins[i].click()
    check(`Sample marker ${i + 1} selects a route`, await page.evaluate(() => document.querySelectorAll('.map-pin.selected').length === 1 && document.querySelector('.route-result').textContent.includes('walk')))
  }
  await page.click('[aria-label="Zoom in on sample map"]')
  await page.click('[aria-label="Zoom in on sample map"]')
  check('Zoom upper limit disables control', await page.$eval('[aria-label="Zoom in on sample map"]', el => el.disabled))
  await page.click('[aria-label="Zoom out on sample map"]')
  await page.click('[aria-label="Reset map"]')
  check('Reset clears route and zoom', await page.evaluate(() => !document.querySelector('.map-pin.selected') && document.querySelector('[aria-label="Zoom out on sample map"]').disabled))
  await page.click('.hero-secondary')
  check('Office shortcut focuses search', await page.evaluate(() => document.activeElement.id === 'place-search' && document.querySelector('[role=combobox]').getAttribute('aria-expanded') === 'true'))
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  check('Keyboard office selection shows floor directions', await page.evaluate(() => Boolean(document.querySelector('.floor-plan')) && document.querySelector('.directions').textContent.includes('Floor 2')))
  await page.click('.text-button')
  await page.click('#place-search')
  await page.type('#place-search', 'not-a-place')
  check('Empty search explains recovery', await page.$eval('.search-options', el => el.textContent.includes('Try')))
  await page.keyboard.press('Escape')
  check('Escape closes search', await page.$eval('#place-search', el => el.getAttribute('aria-expanded') === 'false'))
  for (let i = 0; i < 4; i++) {
    const feature = (await page.$$('.feature-art'))[i]
    await feature.click()
    check(`Feature ${i + 1} opens sample search`, await page.evaluate(() => document.activeElement.id === 'place-search' && document.querySelector('#place-search').value.length > 0))
    await page.keyboard.press('Tab')
    check(`Tab dismisses feature ${i + 1} suggestions`, await page.$eval('#place-search', el => el.getAttribute('aria-expanded') === 'false'))
  }
  for (const theme of ['dark', 'light']) {
    await page.click('.theme-toggle')
    check(`${theme} mode toggle`, await page.evaluate(expected => document.documentElement.dataset.theme === expected, theme))
    await page.setViewport({ width: 375, height: 900 })
    check(`${theme} mode has no mobile overflow`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await page.setViewport({ width: 1280, height: 800 })
  }
  await page.setViewport({ width: 375, height: 900 })
  await page.click('.menu-toggle')
  check('Mobile menu opens', await page.$eval('.menu-toggle', el => el.getAttribute('aria-expanded') === 'true'))
  await page.keyboard.press('Escape')
  check('Escape closes menu and restores focus', await page.evaluate(() => document.activeElement.classList.contains('menu-toggle') && document.querySelector('.menu-toggle').getAttribute('aria-expanded') === 'false'))
  await page.click('.menu-toggle')
  await page.click('.main-nav a')
  check('Menu link closes menu', await page.$eval('.menu-toggle', el => el.getAttribute('aria-expanded') === 'false'))
  await page.$eval('.feature-grid', el => el.scrollTo({ left: 0, behavior: 'instant' }))
  await page.waitForFunction(() => document.querySelector('.carousel-controls button:first-child').disabled)
  await page.click('.carousel-controls .next')
  await wait()
  check('Carousel advances', await page.$eval('.feature-grid', el => el.scrollLeft > 0))
  await page.click('.carousel-controls button:first-child')
  await page.waitForFunction(() => document.querySelector('.carousel-controls button:first-child').disabled)
  check('Carousel returns and disables previous arrow', await page.$eval('.carousel-controls button:first-child', el => el.disabled))
  await page.evaluate(() => { Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw new Error('Clipboard denied') } } }) })
  await page.click('.visitor-copy .button')
  check('Clipboard failure offers visible copy field', await page.$eval('.copy-fallback input', el => el.readOnly && el.value.startsWith('http')))
  await page.evaluate(() => { navigator.clipboard.writeText = async () => {} })
  await page.click('.visitor-copy .button')
  check('Copy success is announced', await page.$eval('.copy-status', el => el.textContent.includes('copied')))
  check('Reduced motion disables smooth scrolling', await page.evaluate(() => getComputedStyle(document.documentElement).scrollBehavior === 'auto'))
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: '.hallmark/mobile-polished.png', fullPage: true })
  await page.setViewport({ width: 1440, height: 1000 })
  await page.screenshot({ path: '.hallmark/desktop-polished.png', fullPage: true })
  check('No JavaScript exceptions', errors.length === 0)
  await writeFile('.hallmark/browser-checks.json', JSON.stringify({ checks, errors }, null, 2))
} finally { await browser.close() }
